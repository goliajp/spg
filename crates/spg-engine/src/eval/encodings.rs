/// Look up a single-byte encoding's high-half table by PG name (already
/// upper-cased with separators stripped).
pub(super) fn encoding_table(enc: &str) -> Option<&'static [char; 128]> {
    Some(match enc {
        "LATIN1" | "ISO88591" => &LATIN1_HIGH,
        "LATIN2" | "ISO88592" => &LATIN2_HIGH,
        "LATIN9" | "ISO885915" => &LATIN9_HIGH,
        "KOI8R" | "KOI8" => &KOI8R_HIGH,
        "KOI8U" => &KOI8U_HIGH,
        // v7.38 (T30) — Windows code pages, tables extracted from live PG18.4.
        "WIN1250" | "WINDOWS1250" => &WIN1250_HIGH,
        "WIN1251" | "WINDOWS1251" => &WIN1251_HIGH,
        "WIN1253" | "WINDOWS1253" => &WIN1253_HIGH,
        "WIN1254" | "WINDOWS1254" => &WIN1254_HIGH,
        _ => return None,
    })
}

/// Decode single-byte-encoded bytes to UTF-8 via the high table.
pub(super) fn single_byte_to_utf8(bytes: &[u8], high: &[char; 128], enc: &str) -> Result<String, EvalError> {
    let mut out = String::with_capacity(bytes.len());
    for &b in bytes {
        if b < 0x80 {
            out.push(b as char);
        } else {
            let ch = high[(b - 0x80) as usize];
            if ch == '\u{FFFF}' {
                return Err(EvalError::TypeMismatch {
                    detail: alloc::format!("byte {b:#04x} is not defined in encoding {enc}"),
                });
            }
            out.push(ch);
        }
    }
    Ok(out)
}

/// Encode a UTF-8 string to single-byte bytes via a reverse table lookup.
pub(super) fn utf8_to_single_byte(s: &str, high: &[char; 128], enc: &str) -> Result<Vec<u8>, EvalError> {
    let mut out = Vec::with_capacity(s.len());
    for c in s.chars() {
        if (c as u32) < 0x80 {
            out.push(c as u8);
        } else if let Some(i) = high.iter().position(|&h| h == c) {
            out.push((i + 0x80) as u8);
        } else {
            return Err(EvalError::TypeMismatch {
                detail: alloc::format!("character {c:?} has no representation in encoding {enc}"),
            });
        }
    }
    Ok(out)
}
