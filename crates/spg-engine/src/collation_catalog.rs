//! v7.38.18 (G1) — PostgreSQL 18.4's collation catalogue.
//!
//! `pg_collation` listed three rows where PG lists 880, and that made it
//! the surface `pg_settings` was before this version: a column declared
//! `COLLATE "en_US.utf8"` worked, `information_schema.columns` reported
//! the name, and the catalogue said no such collation existed. A client
//! that resolves a collation by name — pg_dump's COLLATE restoration,
//! psql's `\dO`, an ORM binding a language-specific column — was told
//! the parameter it had just used was not there.
//!
//! These are CANDIDATES, not claims. The row is emitted only when this
//! build can actually perform the name, which is the same shape
//! `canonical_gucs` has: PG's list says what a client may ask for, and
//! SPG's own capability says what it may answer. PG's set is its host's
//! locales, so publishing these 880 verbatim would be claiming to have
//! exactly that container's.
