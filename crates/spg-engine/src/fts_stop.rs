/// Is `w` a stopword of this list? The lists are sorted, so this is a
/// binary search rather than a scan of three hundred strings per token.
pub(crate) fn is_stop(list: &[&str], w: &str) -> bool {
    list.binary_search(&w).is_ok()
}
