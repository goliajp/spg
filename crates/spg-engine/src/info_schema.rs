//! `meta view … is not yet materialisable`** — among them
//! `data_type_privileges` (which `element_types` depends on),
//! `collations`, `user_defined_types`, `routine_privileges` and the
//! whole `role_*_grants` family. A tool that reflects through
//! `information_schema` — every ORM does — got an error rather than an
//! empty set.
//!
//! The columns below are read off PostgreSQL 18.6's own
//! `information_schema.columns` (696 rows over 69 relations), in its
//! ordinal order. A relation here has a SHAPE; whether it has rows is
//! the materialiser's question. The ones SPG is genuinely empty of
//! answer zero rows with the right columns, which is what PostgreSQL
//! answers for them too on a database with no foreign data wrappers,
//! no user mappings and no transforms.

