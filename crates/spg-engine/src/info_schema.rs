/// 9.0.0 (N23) — the relations derived from the catalog SPG already
/// has: its collations, its roles, its domains, its views' bodies and
/// its constraints. Measured against PostgreSQL 18.6 on a fixed schema,
/// row for row.
///
/// `None` when `view` is not one of them.
pub(crate) fn synth_derived_info_schema(
    view: &str,
    cat: &spg_storage::Catalog,
    catalog_name: &str,
    roles: &[alloc::string::String],
) -> Option<(Vec<ColumnSchema>, Vec<Row<'static>>)> {
    let bare = view.strip_prefix("__spg_info_")?;
    let cols = info_schema_columns(bare)?;
    let cat_name = || Value::text(alloc::string::String::from(catalog_name));
    let rows: Vec<Row<'static>> = match bare {
        // Every collation the catalog publishes. PG 18.6 reports
        // `NO PAD` for all of them (the SQL standard's other value,
        // `PAD SPACE`, is what `bpchar` comparison does, and PG models
        // that on the TYPE rather than the collation).
        "collations" => published_collations()
            .map(|name| {
                Row::new(alloc::vec![
                    cat_name(),
                    Value::text("pg_catalog"),
                    Value::text(name),
                    Value::text("NO PAD"),
                ])
            })
            .collect(),
        // One row per collation, naming the one character set. PG's
        // three character-set columns read NULL, NULL, 'UTF8'.
        "collation_character_set_applicability" => published_collations()
            .map(|name| {
                Row::new(alloc::vec![
                    cat_name(),
                    Value::text("pg_catalog"),
                    Value::text(name),
                    Value::Null,
                    Value::Null,
                    Value::text("UTF8"),
                ])
            })
            .collect(),
        // The roles the session can use. PG lists the current role and
        // everything it inherits; SPG's directory is the same source
        // `pg_roles` answers from.
        "enabled_roles" => roles
            .iter()
            .map(|r| Row::new(alloc::vec![Value::text(r.clone())]))
            .collect(),
        // A grant of a role to a role. SPG records no role membership,
        // which is why this is empty rather than absent — PG answers
        // rows here only once `GRANT <role> TO <role>` has run.
        "applicable_roles" | "administrable_role_authorizations" => Vec::new(),
        // A domain's underlying type, and its constraints.
        "domain_udt_usage" => cat
            .domain_types()
            .values()
            .map(|d| {
                Row::new(alloc::vec![
                    cat_name(),
                    Value::text("pg_catalog"),
                    Value::text(alloc::string::String::from(
                        crate::system_catalog::udt_name_for(&ColumnSchema::new(
                            "v",
                            d.base_type,
                            true,
                        )),
                    )),
                    cat_name(),
                    Value::text("public"),
                    Value::text(d.name.clone()),
                ])
            })
            .collect(),
        "domain_constraints" => cat
            .domain_types()
            .values()
            .flat_map(|d| {
                d.checks.iter().map(move |c| {
                    Row::new(alloc::vec![
                        cat_name(),
                        Value::text("public"),
                        Value::text(c.name.clone()),
                        cat_name(),
                        Value::text("public"),
                        Value::text(d.name.clone()),
                        Value::text("NO"),
                        Value::text("NO"),
                    ])
                })
            })
            .collect(),
        // Each column's own type, named as the catalog names it.
        "column_udt_usage" => cat
            .visible_table_names()
            .into_iter()
            .filter_map(|t| cat.get(&t).map(|tb| (t, tb)))
            .flat_map(|(tname, tb)| {
                tb.schema()
                    .columns
                    .iter()
                    .map(|c| {
                        Row::new(alloc::vec![
                            cat_name(),
                            Value::text("pg_catalog"),
                            Value::text(udt_name_of(c)),
                            cat_name(),
                            Value::text("public"),
                            Value::text(tname.clone()),
                            Value::text(c.name.clone()),
                        ])
                    })
                    .collect::<Vec<_>>()
            })
            .collect(),
        // A column whose type is a DOMAIN.
        "column_domain_usage" => cat
            .visible_table_names()
            .into_iter()
            .filter_map(|t| cat.get(&t).map(|tb| (t, tb)))
            .flat_map(|(tname, tb)| {
                tb.schema()
                    .columns
                    .iter()
                    .filter_map(|c| {
                        let d = c.user_domain_type.as_ref()?;
                        Some(Row::new(alloc::vec![
                            cat_name(),
                            Value::text("public"),
                            Value::text(d.clone()),
                            cat_name(),
                            Value::text("public"),
                            Value::text(tname.clone()),
                            Value::text(c.name.clone()),
                        ]))
                    })
                    .collect::<Vec<_>>()
            })
            .collect(),
        // Which TABLES a view reads, and which COLUMNS of them. Readable
        // because D9 expands `*` at CREATE, so the stored body names
        // every column; a body that still carries one contributes its
        // tables and no columns rather than guessing.
        "view_table_usage" => view_usage(cat, catalog_name, false),
        "view_column_usage" => view_usage(cat, catalog_name, true),
        // The table each constraint is ON. PG names the constraint's
        // own index for a key; SPG's naming helper is the one
        // `pg_constraint` already uses.
        "constraint_table_usage" => cat
            .visible_table_names()
            .into_iter()
            .filter_map(|tname| cat.get(&tname).map(|tb| (tname, tb)))
            .flat_map(|(tname, tb)| {
                let mut out: Vec<Row<'static>> = Vec::new();
                for uc in &tb.schema().uniqueness_constraints {
                    out.push(constraint_usage_row(
                        catalog_name,
                        &tname,
                        &crate::system_catalog::pg_unique_conname(tb, uc, &tname),
                    ));
                }
                for fk in &tb.schema().foreign_keys {
                    // A foreign key is listed against the table it
                    // REFERENCES, which is what `constraint_table_usage`
                    // means: the tables a constraint depends on. The
                    // NAME comes from the helper `pg_constraint` uses —
                    // spelling it again here gave `isf_b_fk0` where the
                    // catalog next door said `isf_b_a_id_fkey`.
                    out.push(constraint_usage_row(
                        catalog_name,
                        &fk.parent_table,
                        &crate::system_catalog::pg_fk_conname(tb, fk, &tname),
                    ));
                }
                out
            })
            .collect(),
        // A composite type is `STRUCTURED` here; PG leaves every other
        // column NULL for one, and reports `is_instantiable` YES.
        "user_defined_types" => cat
            .composite_types()
            .keys()
            .map(|name| {
                let mut v = alloc::vec![
                    cat_name(),
                    Value::text("public"),
                    Value::text(name.clone()),
                    Value::text("STRUCTURED"),
                    Value::text("YES"),
                ];
                v.resize(29, Value::Null);
                Row::new(v)
            })
            .collect(),
        // A column whose type is an ARRAY: its element type, keyed by
        // the column's attnum the way PG keys it (`a1`, `a2`).
        "element_types" => cat
            .visible_table_names()
            .into_iter()
            .filter_map(|tname| cat.get(&tname).map(|tb| (tname, tb)))
            .flat_map(|(tname, tb)| {
                tb.schema()
                    .columns
                    .iter()
                    .enumerate()
                    .filter_map(|(i, c)| {
                        let elem = crate::conversions::array_element_type(c.ty)?;
                        let attnum = i + 1;
                        let probe = ColumnSchema::new("v", elem, true);
                        let mut v = alloc::vec![
                            cat_name(),
                            Value::text("public"),
                            Value::text(tname.clone()),
                            Value::text("TABLE"),
                            Value::text(alloc::format!("{attnum}")),
                            Value::text(crate::conversions::pg_type_name_for_error(elem)),
                        ];
                        // The long tail of length / precision / charset
                        // columns PG leaves NULL for an ordinary
                        // element type, up to `udt_*`.
                        v.resize(20, Value::Null);
                        v.push(cat_name());
                        v.push(Value::text("pg_catalog"));
                        v.push(Value::text(alloc::string::String::from(
                            crate::system_catalog::udt_name_for(&probe),
                        )));
                        v.resize(27, Value::Null);
                        v.push(Value::text(alloc::format!("a{attnum}")));
                        Some(Row::new(v))
                    })
                    .collect::<Vec<_>>()
            })
            .collect(),
        // A GENERATED column and the columns its expression reads.
        "column_column_usage" => cat
            .visible_table_names()
            .into_iter()
            .filter_map(|tname| cat.get(&tname).map(|tb| (tname, tb)))
            .flat_map(|(tname, tb)| {
                let cols: Vec<alloc::string::String> =
                    tb.schema().columns.iter().map(|c| c.name.clone()).collect();
                tb.schema()
                    .columns
                    .iter()
                    .filter_map(|c| c.generated_stored_expr.clone().map(|e| (c.name.clone(), e)))
                    .flat_map(|(dependent, expr)| {
                        let read: Vec<alloc::string::String> = cols
                            .iter()
                            .filter(|n| **n != dependent && expr_names_column(&expr, n))
                            .cloned()
                            .collect();
                        let tname = tname.clone();
                        read.into_iter().map(move |src| {
                            Row::new(alloc::vec![
                                Value::text(alloc::string::String::from(catalog_name)),
                                Value::text("public"),
                                Value::text(tname.clone()),
                                Value::text(src),
                                Value::text(dependent.clone()),
                            ])
                        })
                    })
                    .collect::<Vec<_>>()
            })
            .collect(),
        // USAGE on the objects that have it: every collation, and every
        // domain twice (PUBLIC without the grant option, the owner with
        // it). `role_usage_grants` is the same set seen from the
        // grantee's side, which is how PostgreSQL defines it.
        "usage_privileges" | "role_usage_grants" => {
            let owner = owner_name(roles);
            let mut out: Vec<Row<'static>> = published_collations()
                .map(|name| {
                    usage_row(
                        catalog_name,
                        &owner,
                        "PUBLIC",
                        "pg_catalog",
                        name,
                        "COLLATION",
                        "NO",
                    )
                })
                .collect();
            for d in cat.domain_types().values() {
                out.push(usage_row(
                    catalog_name,
                    &owner,
                    "PUBLIC",
                    "public",
                    &d.name,
                    "DOMAIN",
                    "NO",
                ));
                out.push(usage_row(
                    catalog_name,
                    &owner,
                    &owner,
                    "public",
                    &d.name,
                    "DOMAIN",
                    "YES",
                ));
            }
            out
        }
        // USAGE on a TYPE. PostgreSQL lists every composite type twice,
        // the same way.
        "udt_privileges" | "role_udt_grants" => {
            let owner = owner_name(roles);
            cat.composite_types()
                .keys()
                .flat_map(|name| {
                    let c = || Value::text(alloc::string::String::from(catalog_name));
                    let row = |grantee: &str, grantable: &str| {
                        Row::new(alloc::vec![
                            Value::text(owner.clone()),
                            Value::text(alloc::string::String::from(grantee)),
                            c(),
                            Value::text("public"),
                            Value::text(name.clone()),
                            Value::text("TYPE USAGE"),
                            Value::text(alloc::string::String::from(grantable)),
                        ])
                    };
                    alloc::vec![row("PUBLIC", "NO"), row(&owner, "YES")]
                })
                .collect()
        }
        // One row per place a type is USED: each table column, each
        // composite type's attribute, each domain.
        "data_type_privileges" => {
            let mut out: Vec<Row<'static>> = Vec::new();
            let c = || Value::text(alloc::string::String::from(catalog_name));
            for tname in cat.visible_table_names() {
                let Some(tb) = cat.get(&tname) else { continue };
                for (i, _) in tb.schema().columns.iter().enumerate() {
                    out.push(Row::new(alloc::vec![
                        c(),
                        Value::text("public"),
                        Value::text(tname.clone()),
                        Value::text("TABLE"),
                        Value::text(alloc::format!("{}", i + 1)),
                    ]));
                }
            }
            for (name, def) in cat.composite_types() {
                for i in 0..def.fields.len() {
                    out.push(Row::new(alloc::vec![
                        c(),
                        Value::text("public"),
                        Value::text(name.clone()),
                        Value::text("USER-DEFINED TYPE"),
                        Value::text(alloc::format!("{}", i + 1)),
                    ]));
                }
            }
            for d in cat.domain_types().values() {
                out.push(Row::new(alloc::vec![
                    c(),
                    Value::text("public"),
                    Value::text(d.name.clone()),
                    Value::text("DOMAIN"),
                    Value::text("1"),
                ]));
            }
            out
        }
        // Each user function's parameters. `specific_name` is
        // `<name>_<oid>`, and the oid is the one `pg_proc` gives it —
        // spelled once, so a client that joins the two surfaces lands
        // on the same routine.
        "parameters" => cat
            .functions()
            .values()
            .enumerate()
            .flat_map(|(i, def)| {
                let specific = specific_name_of(def, i);
                parse_args(&def.args_repr)
                    .into_iter()
                    .enumerate()
                    .map(|(j, (pname, ptype, pdefault))| {
                        let probe = arg_column(&ptype);
                        let mut v = alloc::vec![
                            Value::text(alloc::string::String::from(catalog_name)),
                            Value::text("public"),
                            Value::text(specific.clone()),
                            #[allow(clippy::cast_possible_wrap)]
                            Value::Int((j + 1) as i32),
                            Value::text("IN"),
                            Value::text("NO"),
                            Value::text("NO"),
                            pname.map_or(Value::Null, Value::text),
                            Value::text(probe.as_ref().map_or_else(
                                || ptype.clone(),
                                |c| crate::conversions::pg_type_name_for_error(c.ty),
                            ),),
                        ];
                        v.resize(23, Value::Null);
                        v.push(Value::text(alloc::string::String::from(catalog_name)));
                        v.push(Value::text("pg_catalog"));
                        v.push(Value::text(probe.as_ref().map_or_else(
                            || ptype.clone(),
                            |c| alloc::string::String::from(crate::system_catalog::udt_name_for(c)),
                        )));
                        v.resize(30, Value::Null);
                        #[allow(clippy::cast_possible_wrap)]
                        v.push(Value::text(alloc::format!("{}", j + 1)));
                        v.push(pdefault.map_or(Value::Null, Value::text));
                        Row::new(v)
                    })
                    .collect::<Vec<_>>()
            })
            .collect(),
        // EXECUTE on each user function: the owner with the grant
        // option, PUBLIC without it, as PostgreSQL's default grant is.
        "routine_privileges" | "role_routine_grants" => {
            let owner = owner_name(roles);
            cat.functions()
                .values()
                .enumerate()
                .flat_map(|(i, def)| {
                    let specific = specific_name_of(def, i);
                    let c = || Value::text(alloc::string::String::from(catalog_name));
                    let row = |grantee: &str, grantable: &str| {
                        Row::new(alloc::vec![
                            Value::text(owner.clone()),
                            Value::text(alloc::string::String::from(grantee)),
                            c(),
                            Value::text("public"),
                            Value::text(specific.clone()),
                            c(),
                            Value::text("public"),
                            Value::text(def.name.clone()),
                            Value::text("EXECUTE"),
                            Value::text(alloc::string::String::from(grantable)),
                        ])
                    };
                    alloc::vec![row(&owner, "YES"), row("PUBLIC", "NO")]
                })
                .collect()
        }
        // A routine's dependencies on other objects. PostgreSQL records
        // these for a SQL-bodied function only, and answers zero rows
        // for one whose body it stored as text — which is every
        // function here, since SPG re-parses a body at CALL time rather
        // than resolving it at CREATE. Listed with the right columns
        // and no rows rather than refused.
        "routine_column_usage"
        | "routine_table_usage"
        | "routine_sequence_usage"
        | "routine_routine_usage"
        | "check_constraint_routine_usage"
        | "view_routine_usage" => Vec::new(),
        // `UPDATE OF <column>` triggers. SPG records a trigger's event
        // without the column list, so there is nothing to report and
        // PostgreSQL answers zero rows for a trigger without one too.
        "triggered_update_columns" => Vec::new(),
        _ => return None,
    };
    Some((cols, rows))
}

/// `information_schema`'s `specific_name`: the routine's name and the
/// oid `pg_proc` gives it.
fn specific_name_of(def: &spg_storage::FunctionDef, i: usize) -> alloc::string::String {
    #[allow(clippy::cast_possible_wrap)]
    let oid = crate::system_catalog::OID_FUNC_BASE + 1 + i as i64;
    alloc::format!("{}_{oid}", def.name)
}

/// A function's declared arguments, as `(name, type, default)`.
///
/// `args_repr` is the canonical display form the parser stored
/// (`"(x INT, y TEXT DEFAULT 'a')"`); reading it back is what
/// `pg_proc.proargnames` already does.
fn parse_args(
    args_repr: &str,
) -> Vec<(
    Option<alloc::string::String>,
    alloc::string::String,
    Option<alloc::string::String>,
)> {
    let inner = args_repr
        .trim()
        .trim_start_matches('(')
        .trim_end_matches(')');
    if inner.trim().is_empty() {
        return Vec::new();
    }
    inner
        .split(',')
        .map(|a| {
            let a = a.trim();
            let (head, dflt) = match a.to_ascii_uppercase().find(" DEFAULT ") {
                Some(i) => (
                    a[..i].trim(),
                    Some(alloc::string::String::from(
                        a[i + " DEFAULT ".len()..].trim(),
                    )),
                ),
                None => (a, None),
            };
            let mut parts = head.split_whitespace();
            let first = parts.next().unwrap_or("").trim();
            let rest: alloc::string::String = parts.collect::<Vec<_>>().join(" ");
            if rest.is_empty() {
                // No name: the whole thing is the type.
                (None, alloc::string::String::from(first), dflt)
            } else {
                (Some(alloc::string::String::from(first)), rest, dflt)
            }
        })
        .collect()
}

/// A probe column of an argument's declared type, for the two type
/// names `parameters` reports.
fn arg_column(type_name: &str) -> Option<ColumnSchema> {
    crate::conversions::type_name_to_data_type(&type_name.to_ascii_lowercase())
        .map(|ty| ColumnSchema::new("v", ty, true))
}

/// One `usage_privileges` / `role_usage_grants` row — the two carry the
/// same columns and PostgreSQL derives the second from the first.
fn usage_row(
    catalog_name: &str,
    grantor: &str,
    grantee: &str,
    schema: &str,
    object: &str,
    object_type: &str,
    grantable: &str,
) -> Row<'static> {
    let c = || Value::text(alloc::string::String::from(catalog_name));
    Row::new(alloc::vec![
        Value::text(alloc::string::String::from(grantor)),
        Value::text(alloc::string::String::from(grantee)),
        c(),
        Value::text(alloc::string::String::from(schema)),
        Value::text(alloc::string::String::from(object)),
        Value::text(alloc::string::String::from(object_type)),
        Value::text("USAGE"),
        Value::text(alloc::string::String::from(grantable)),
    ])
}

/// The role these grants are FROM. SPG has one owner; PostgreSQL names
/// the bootstrap superuser, which is the first login role here.
fn owner_name(roles: &[alloc::string::String]) -> alloc::string::String {
    roles
        .first()
        .cloned()
        .unwrap_or_else(|| alloc::string::String::from("postgres"))
}

/// Does this expression source name that column?
fn expr_names_column(src: &str, column: &str) -> bool {
    use spg_sql::ast::Expr;
    let Ok(mut e) = spg_sql::parser::parse_expression(src) else {
        return false;
    };
    let mut found = false;
    let Ok(()) = e.for_each_node_mut::<core::convert::Infallible>(
        &mut |node| {
            if let Expr::Column(c) = node
                && c.name.eq_ignore_ascii_case(column)
            {
                found = true;
            }
            Ok(())
        },
        &mut |_| Ok(()),
    );
    found
}

/// One `constraint_table_usage` row.
fn constraint_usage_row(catalog_name: &str, table: &str, constraint: &str) -> Row<'static> {
    let c = || Value::text(alloc::string::String::from(catalog_name));
    Row::new(alloc::vec![
        c(),
        Value::text("public"),
        Value::text(alloc::string::String::from(table)),
        c(),
        Value::text("public"),
        Value::text(alloc::string::String::from(constraint)),
    ])
}

/// `view_table_usage` and `view_column_usage`: the relations a view
/// reads, and — when `with_columns` — which of their columns.
fn view_usage(
    cat: &spg_storage::Catalog,
    catalog_name: &str,
    with_columns: bool,
) -> Vec<Row<'static>> {
    let c = || Value::text(alloc::string::String::from(catalog_name));
    let mut out: Vec<Row<'static>> = Vec::new();
    for (vname, def) in cat.views_all() {
        let Ok(spg_sql::ast::Statement::Select(sel)) = spg_sql::parser::parse_statement(&def.body)
        else {
            continue;
        };
        let Some(from) = &sel.from else { continue };
        for r in core::iter::once(&from.primary).chain(from.joins.iter().map(|j| &j.table)) {
            let Some(tb) = cat.get(&r.name) else { continue };
            if with_columns {
                let label = r.alias.as_ref().unwrap_or(&r.name);
                for col in &tb.schema().columns {
                    if !view_names_column(&sel, label, &col.name) {
                        continue;
                    }
                    out.push(Row::new(alloc::vec![
                        c(),
                        Value::text("public"),
                        Value::text(vname.clone()),
                        c(),
                        Value::text("public"),
                        Value::text(r.name.clone()),
                        Value::text(col.name.clone()),
                    ]));
                }
            } else {
                out.push(Row::new(alloc::vec![
                    c(),
                    Value::text("public"),
                    Value::text(vname.clone()),
                    c(),
                    Value::text("public"),
                    Value::text(r.name.clone()),
                ]));
            }
        }
    }
    out
}

/// Does this view body name `table_label.column` — or `column` bare?
fn view_names_column(sel: &spg_sql::ast::SelectStatement, label: &str, column: &str) -> bool {
    use spg_sql::ast::{Expr, SelectItem};
    let mut found = false;
    let mut look = |e: &Expr| {
        let mut probe = e.clone();
        let Ok(()) = probe.for_each_node_mut::<core::convert::Infallible>(
            &mut |node| {
                if let Expr::Column(cn) = node
                    && cn.name.eq_ignore_ascii_case(column)
                    && cn
                        .qualifier
                        .as_ref()
                        .is_none_or(|q| q.eq_ignore_ascii_case(label))
                {
                    found = true;
                }
                Ok(())
            },
            &mut |_| Ok(()),
        );
    };
    for it in &sel.items {
        if let SelectItem::Expr { expr, .. } = it {
            look(expr);
        }
    }
    if let Some(w) = &sel.where_ {
        look(w);
    }
    if let Some(from) = &sel.from {
        for j in &from.joins {
            if let Some(on) = &j.on {
                look(on);
            }
        }
    }
    found
}

/// The type name `information_schema` gives a column — PostgreSQL's own
/// internal name (`int4`, `varchar`), not the SQL spelling. The one
/// mapping `information_schema.columns` already uses.
fn udt_name_of(c: &ColumnSchema) -> alloc::string::String {
    if let Some(e) = &c.user_enum_type {
        return e.clone();
    }
    if let Some(d) = &c.user_domain_type {
        return d.clone();
    }
    alloc::string::String::from(crate::system_catalog::udt_name_for(c))
}

/// The collations `pg_collation` publishes — the same filter, so the
/// two surfaces cannot list different sets.
fn published_collations() -> impl Iterator<Item = &'static str> {
    crate::collation_catalog::PG_COLLATIONS
        .iter()
        .filter(|(_, name, provider, ..)| *provider == "d" || crate::collate::is_supported(name))
        .map(|(_, name, ..)| *name)
}
