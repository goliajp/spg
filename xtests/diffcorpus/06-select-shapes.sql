SELECT 'T03'; SELECT id FROM dc ORDER BY g NULLS FIRST FETCH FIRST 2 ROWS WITH TIES;
SELECT 'T04'; SELECT id FROM dc WHERE id < 3 UNION SELECT id FROM dc WHERE id > 3 ORDER BY 1;
SELECT 'T05'; SELECT id FROM dc UNION ALL SELECT id FROM dc ORDER BY 1 LIMIT 3;
SELECT 'T06'; SELECT id FROM dc INTERSECT SELECT id FROM dc WHERE id > 2 ORDER BY 1;
SELECT 'T07'; SELECT id FROM dc EXCEPT SELECT id FROM dc WHERE id > 2 ORDER BY 1;
SELECT 'T08'; SELECT g, id FROM dc a WHERE EXISTS (SELECT 1 FROM dc b WHERE b.g = a.g AND b.id <> a.id) ORDER BY id;
SELECT 'T09'; SELECT id, (SELECT count(*) FROM dc b WHERE b.g = a.g) FROM dc a ORDER BY id;
SELECT 'T10'; SELECT a.id, b.id FROM dc a JOIN dc b ON a.g = b.g AND a.id < b.id ORDER BY 1,2;
SELECT 'T11'; SELECT a.id, b.id FROM dc a LEFT JOIN dc b ON a.id = b.id + 1 ORDER BY 1 NULLS LAST;
SELECT 'T12'; SELECT a.id, b.id FROM dc a FULL JOIN dc b ON a.id = b.id + 3 ORDER BY 1 NULLS LAST, 2 NULLS LAST;
SELECT 'T13'; SELECT a.id, x.v FROM dc a CROSS JOIN LATERAL (SELECT a.id*2 v) x ORDER BY 1;
SELECT 'T14'; SELECT id FROM dc a WHERE a.id = ANY (SELECT id FROM dc WHERE g = 10) ORDER BY 1;
SELECT 'T15'; SELECT id FROM dc a WHERE a.id > ALL (SELECT id FROM dc WHERE id < 3) ORDER BY 1;
SELECT 'T16'; WITH c AS (SELECT g, count(*) n FROM dc GROUP BY g) SELECT * FROM c ORDER BY g NULLS LAST;
SELECT 'T17'; WITH RECURSIVE r(n) AS (SELECT 1 UNION ALL SELECT n+1 FROM r WHERE n<4) SELECT array_agg(n) FROM r;
SELECT 'T18'; SELECT * FROM (VALUES (1,'a'),(2,'b')) t(x,y) ORDER BY x;
SELECT 'T19'; SELECT id, unnest(a) FROM dc WHERE a IS NOT NULL ORDER BY 1,2 NULLS LAST;
SELECT 'T20'; SELECT * FROM generate_series(1,3) t(x) ORDER BY x;
SELECT 'T21'; SELECT * FROM generate_series(1,3) WITH ORDINALITY AS t(x,o) ORDER BY x;
SELECT 'T22'; SELECT g, count(*) FROM dc GROUP BY 1 ORDER BY 1 NULLS LAST;
SELECT 'T23'; SELECT id AS alias FROM dc ORDER BY alias LIMIT 2;
SELECT 'T24'; SELECT id FROM dc WHERE (id, g) IN ((1,10),(2,20)) ORDER BY 1;
