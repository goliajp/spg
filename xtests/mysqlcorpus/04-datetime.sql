-- Date and time in MySQL's spelling. Nothing here reads the clock.
SELECT 'T01', DATE_FORMAT('2020-01-02','%Y-%m-%d'), DATE_FORMAT('2020-01-02 03:04:05','%H:%i:%s');
SELECT 'T02', DATE_ADD('2020-01-02', INTERVAL 1 DAY), DATE_SUB('2020-01-02', INTERVAL 1 MONTH);
SELECT 'T03', '2020-01-02' + INTERVAL 1 DAY, INTERVAL 1 DAY + '2020-01-02';
SELECT 'T04', DATEDIFF('2020-03-01','2020-02-01'), TIMESTAMPDIFF(MONTH,'2020-01-01','2020-03-01');
SELECT 'T05', YEAR('2020-01-02'), MONTH('2020-01-02'), DAY('2020-01-02'), DAYOFWEEK('2020-01-02');
SELECT 'T06', DAYNAME('2020-01-02'), MONTHNAME('2020-01-02'), QUARTER('2020-05-02');
SELECT 'T07', LAST_DAY('2020-02-05'), MAKEDATE(2020,60), DAYOFYEAR('2020-03-01');
SELECT 'T08', TIME('2020-01-02 03:04:05'), DATE('2020-01-02 03:04:05'), HOUR('03:04:05');
SELECT 'T09', SEC_TO_TIME(3661), TIME_TO_SEC('01:01:01'), ADDTIME('01:00:00','00:30:00');
SELECT 'T10', STR_TO_DATE('02/01/2020','%d/%m/%Y'), STR_TO_DATE('x','%d');
SELECT 'T11', UNIX_TIMESTAMP('2020-01-02 00:00:00'), FROM_UNIXTIME(0) IS NOT NULL;
SELECT 'T12', WEEK('2020-01-02'), WEEKDAY('2020-01-02'), YEARWEEK('2020-01-02');
SELECT 'T13', EXTRACT(YEAR FROM '2020-01-02'), EXTRACT(DAY FROM '2020-01-02');
SELECT 'T14', CONVERT_TZ('2020-01-02 00:00:00','+00:00','+02:00');
SELECT 'T15', made, DATE(made) FROM mc_t ORDER BY id;
